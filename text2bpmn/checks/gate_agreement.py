"""The soundness gate's own check against WOFLAN, model by model.

    python3 -m text2bpmn.checks.soundness FOLDER [...] --out OUT     # WOFLAN's verdicts
    python3 -m text2bpmn.checks.gate_agreement OUT/soundness.json    # -> text2bpmn/results/soundness_gate_agreement.md

text2bpmn/soundness_gate.py decides soundness itself, by playing each model's
token game, so that a run does not need pm4py. This sets its verdict beside
WOFLAN's for every model WOFLAN judged, and lists every model on which they
differ. For each of those it asks a third judge: WOFLAN's own input, the
Petri net pm4py converts the model into, explored marking by marking with
pm4py's own firing rule, which decides classical soundness by its definition
(option to complete, proper completion, no dead transition). WOFLAN may also
reject a net that is not covered by S-components, a structural test.
"""
import argparse
import json
from collections import Counter, defaultdict, deque
from pathlib import Path

from text2bpmn.soundness_gate import check, graph_of_bpmn

OUT = Path("text2bpmn/results/soundness_gate_agreement")


def explored(path, limit=200_000):
    """Classical soundness of pm4py's net for the model, from its reachable markings."""
    import pm4py
    from pm4py.objects.petri_net import semantics

    net, im, fm = pm4py.convert_to_petri_net(pm4py.read_bpmn(str(path)))
    key = lambda m: frozenset((p.name, c) for p, c in m.items() if c)  # noqa: E731
    final, seen, queue, back, fired = key(fm), {key(im)}, deque([im]), defaultdict(set), set()
    while queue:
        m = queue.popleft()
        if all(m[p] >= c for p, c in fm.items()) and key(m) != final:
            return "unsound (the end is reached with tokens left)"
        for t in semantics.enabled_transitions(net, m):
            n = semantics.execute(t, net, m)
            fired.add(t.name)
            back[key(n)].add(key(m))
            if key(n) not in seen:
                if len(seen) > limit:
                    return "unknown"
                seen.add(key(n))
                queue.append(n)
    if final not in seen:
        return "unsound (the end is never reached)"
    completes, stack = {final}, [final]
    while stack:
        for b in back[stack.pop()]:
            if b not in completes:
                completes.add(b)
                stack.append(b)
    if len(completes) != len(seen):
        return "unsound (a deadlock)"
    if any(t.name not in fired for t in net.transitions):
        return "unsound (a dead transition)"
    return f"sound ({len(seen)} markings)"


def label(sound):
    return "sound" if sound is True else "unknown" if sound is None else "unsound"


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("woflan", help="a soundness.json written by text2bpmn.checks.soundness")
    ap.add_argument("--strip", default="", help="a path prefix to leave out of the report")
    ap.add_argument("--note", default="", help="a sentence on the folders, for the report")
    args = ap.parse_args()
    report = json.loads(Path(args.woflan).read_text(encoding="utf-8"))
    pairs, differ = Counter(), []
    for folder, result in report["folders"].items():
        for model, outcome in result["per_model"].items():
            path = Path(folder) / model
            mine = label(check(*graph_of_bpmn(path))["sound"])
            theirs = outcome["status"]
            pairs[(theirs, mine)] += 1
            if theirs != mine:
                reason = "; ".join(m for m in outcome.get("messages", []) if "covered" in m or "lock" in m)
                differ.append((str(path).replace(args.strip, ""), theirs, mine, explored(path), reason))
    folders = [f.replace(args.strip, "") for f in report["folders"]]
    total = sum(pairs.values())
    agree = sum(n for (a, b), n in pairs.items() if a == b)
    lines = ["# The soundness gate's check against WOFLAN", "",
             "Generated by `text2bpmn/checks/gate_agreement.py`: for every model WOFLAN judged "
             "(`text2bpmn/checks/soundness.py`, pm4py), the verdict of `text2bpmn/soundness_gate.py`, which plays "
             "the model's token game.", "",
             f"**{agree} of {total} models agree.**", "",
             "| WOFLAN | token game | models |", "|---|---|---|"]
    lines += [f"| {a} | {b} | {n} |" for (a, b), n in sorted(pairs.items())]
    lines += ["", "Folders: " + ", ".join(f"`{f}`" for f in folders) + "." + (f" {args.note}" if args.note else "")]
    if differ:
        lines += ["", "Models on which they differ, with the verdict of pm4py's own net explored marking by "
                  "marking (classical soundness by its definition) and WOFLAN's reason:", "",
                  "| model | WOFLAN | token game | pm4py's net, explored | WOFLAN's reason |",
                  "|---|---|---|---|---|"]
        lines += [f"| `{p}` | {a} | {b} | {x} | {r} |" for p, a, b, x, r in differ]
    OUT.with_suffix(".md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    OUT.with_suffix(".json").write_text(json.dumps({"pairs": {f"{a}|{b}": n for (a, b), n in pairs.items()},
                                                    "differ": differ, "folders": folders}, indent=2),
                                        encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
